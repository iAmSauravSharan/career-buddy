#!/usr/bin/env node
// gen-routes.mjs — writes src/routes.gen.ts, the static table of every
// src/routes/**/route.ts the server mounts.
//
// Routes keep the file-system convention they had as Next.js route handlers:
// the path is the directory, a `[name]` segment is a path parameter, and each
// file exports one function per HTTP method taking `(req, { params })`. A
// static table (instead of walking the tree at startup) lets a bundler see
// every route, and `--check` lets CI fail when the table is stale.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const srcDir = path.join(here, "..", "src");
const routesDir = path.join(srcDir, "routes");
const outFile = path.join(srcDir, "routes.gen.ts");

function walk(dir) {
  const out = [];
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) out.push(...walk(full));
    else if (entry.name === "route.ts") out.push(full);
  }
  return out;
}

// Static segments sort before parameters so `/a/b` never loses to `/a/:x`.
function sortKey(urlPath) {
  return urlPath.split("/").map((seg) => (seg.startsWith(":") ? `~${seg}` : seg)).join("/");
}

export function renderRoutes() {
  const entries = walk(routesDir)
    .map((file) => {
      const rel = path.relative(routesDir, path.dirname(file)).split(path.sep).join("/");
      const urlPath = `/api/${rel}`.replace(/\[([^\]]+)\]/g, ":$1");
      const importPath = `./routes/${rel}/route`;
      return { urlPath, importPath };
    })
    .sort((a, b) => (sortKey(a.urlPath) < sortKey(b.urlPath) ? -1 : 1));

  const lines = [
    "// GENERATED by scripts/gen-routes.mjs — do not edit. Run `npm run gen:routes`.",
    'import type { RouteModule } from "./route-module";',
    ...entries.map((e, i) => `import * as r${i} from "${e.importPath}";`),
    "",
    "export const routes: { path: string; mod: RouteModule }[] = [",
    ...entries.map((e, i) => `  { path: "${e.urlPath}", mod: r${i} },`),
    "];",
    "",
  ];
  return lines.join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const next = renderRoutes();
  const current = fs.existsSync(outFile) ? fs.readFileSync(outFile, "utf8") : "";
  if (process.argv.includes("--check")) {
    if (current !== next) {
      console.error("src/routes.gen.ts is stale — run `npm run gen:routes`.");
      process.exit(1);
    }
  } else if (current !== next) {
    fs.writeFileSync(outFile, next);
    console.error(`wrote ${path.relative(process.cwd(), outFile)}`);
  }
}
